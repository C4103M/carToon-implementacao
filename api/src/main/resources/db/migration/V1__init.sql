CREATE TABLE IF NOT EXISTS oficina (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    endereco VARCHAR(255),
    telefone VARCHAR(255),
    email VARCHAR(255),
    valor_hora NUMERIC(12, 2),
    taxa_risco NUMERIC(6, 4),
    margem_peca NUMERIC(6, 4),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_oficina_nome UNIQUE (nome),
    CONSTRAINT uk_oficina_telefone UNIQUE (telefone),
    CONSTRAINT uk_oficina_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    oficina_id INTEGER,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT fk_usuario_oficina FOREIGN KEY (oficina_id) REFERENCES oficina (id)
);

CREATE TABLE IF NOT EXISTS cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    cpf VARCHAR(11) NOT NULL,
    endereco VARCHAR(255),
    telefone VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    oficina_id INTEGER NOT NULL,
    CONSTRAINT uk_cliente_oficina_cpf UNIQUE (oficina_id, cpf),
    CONSTRAINT fk_cliente_oficina FOREIGN KEY (oficina_id) REFERENCES oficina (id)
);

CREATE TABLE IF NOT EXISTS veiculo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL,
    marca VARCHAR(255) NOT NULL,
    modelo VARCHAR(255) NOT NULL,
    ano_modelo INTEGER,
    combustivel VARCHAR(255),
    codigo_fipe VARCHAR(20),
    valor_fipe NUMERIC(12, 2),
    mes_referencia VARCHAR(50),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    cliente_id INTEGER NOT NULL,
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

CREATE TABLE IF NOT EXISTS peca (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    fabricante VARCHAR(255) NOT NULL,
    valor_base NUMERIC(38, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    oficina_id INTEGER NOT NULL,
    CONSTRAINT fk_peca_oficina FOREIGN KEY (oficina_id) REFERENCES oficina (id)
);

CREATE TABLE IF NOT EXISTS servico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tempo TIME(6),
    descricao VARCHAR(255),
    peso_servico NUMERIC(3, 1),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    oficina_id INTEGER NOT NULL,
    CONSTRAINT fk_servico_oficina FOREIGN KEY (oficina_id) REFERENCES oficina (id)
);

CREATE TABLE IF NOT EXISTS ordem_servico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT,
    descricao VARCHAR(255) NOT NULL,
    data_orcamento DATE,
    data_rejeicao DATE,
    data_inicio DATE,
    data_finalizacao DATE,
    desconto VARCHAR(255),
    valor_bruto NUMERIC(38, 2),
    valor_desconto NUMERIC(38, 2),
    total NUMERIC(38, 2),
    status_servico VARCHAR(255) NOT NULL,
    oficina_id INTEGER NOT NULL,
    mecanico_id INTEGER NOT NULL,
    veiculo_id INTEGER NOT NULL,
    CONSTRAINT fk_ordem_servico_oficina FOREIGN KEY (oficina_id) REFERENCES oficina (id),
    CONSTRAINT fk_ordem_servico_mecanico FOREIGN KEY (mecanico_id) REFERENCES usuario (id),
    CONSTRAINT fk_ordem_servico_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo (id)
);

CREATE TABLE IF NOT EXISTS item_peca (
